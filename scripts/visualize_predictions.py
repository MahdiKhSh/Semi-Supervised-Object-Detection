#!/usr/bin/env python3
"""Save real, reproducible detector overlays for paper qualitative analysis.

Never alters original images and does not invent detections. Local only.
"""
import argparse
from pathlib import Path

import torch
from PIL import Image, ImageDraw
from torchvision.transforms.functional import to_tensor

from ssod_research.native_training import build_model, BDD_CLASSES


def visualize(checkpoint, images, output, *, max_images=20, max_side=640,
              threshold=0.5, device="auto"):
    source = Path(images)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    paths = sorted(p for p in source.rglob("*") if p.suffix.lower() in (".jpg", ".jpeg", ".png"))
    if not paths:
        raise ValueError(f"No images found in {source}")
    dest = torch.device("cuda" if device == "auto" and torch.cuda.is_available()
                        else "cpu" if device == "auto" else device)
    model = build_model(pretrained_backbone=False, max_side=max_side).to(dest)
    # Trusted checkpoints generated by this research code only.
    state = torch.load(checkpoint, map_location="cpu", weights_only=False)
    weights = state.get("teacher") or state.get("student")
    if weights is None:
        raise ValueError("checkpoint has neither teacher nor student weights")
    model.load_state_dict(weights, strict=True)
    model.eval()
    records = []
    with torch.inference_mode():
        for path in paths[:max_images]:
            with Image.open(path) as im:
                image = im.convert("RGB")
            w, h = image.size
            scale = min(1.0, max_side / max(w, h))
            if scale < 1:
                image = image.resize((max(1, round(w*scale)), max(1, round(h*scale))),
                                     Image.Resampling.BILINEAR)
            prediction = model([to_tensor(image).to(dest)])[0]
            draw = ImageDraw.Draw(image)
            n = 0
            for box, label, score in zip(prediction["boxes"].cpu().tolist(),
                                         prediction["labels"].cpu().tolist(),
                                         prediction["scores"].cpu().tolist()):
                if float(score) < threshold or not 1 <= int(label) < len(BDD_CLASSES):
                    continue
                x1, y1, x2, y2 = box
                draw.rectangle((x1, y1, x2, y2), outline=(245, 235, 0), width=2)
                draw.text((x1, max(0, y1 - 15)), f"{BDD_CLASSES[int(label)]}: {score:.2f}",
                          fill=(245, 235, 0))
                n += 1
            destination = output / path.name
            image.save(destination)
            records.append({"file": str(destination), "detections_above_threshold": n})
    return records


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--images", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--max-images", type=int, default=20)
    p.add_argument("--max-side", type=int, default=640)
    p.add_argument("--threshold", type=float, default=0.5)
    p.add_argument("--device", choices=("auto", "cuda", "cpu"), default="auto")
    args = p.parse_args()
    results = visualize(args.checkpoint, args.images, args.output,
                        max_images=args.max_images, max_side=args.max_side,
                        threshold=args.threshold, device=args.device)
    print(f"Saved {len(results)} **real detector visualizations** in {args.output}")


if __name__ == "__main__":
    main()
